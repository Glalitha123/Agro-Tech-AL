/**
 * @desc    Save recommendation to profile
 * @route   POST /api/crops/treatments/save
 * @access  Private
 */
export const saveTreatment = async (req, res, next) => {
  const { diseaseName, cropType, recommendation } = req.body;

  try {
    const user = await User.findById(req.user._id);
    if (!user) {
      res.status(404);
      return next(new Error('User not found'));
    }

    // Check if already saved
    const exists = user.savedTreatments.some(
      (t) => t.diseaseName.toLowerCase() === diseaseName.toLowerCase()
    );

    if (exists) {
      res.status(400);
      return next(new Error('Treatment already saved to your profile'));
    }

    user.savedTreatments.push({ diseaseName, cropType, recommendation });
    await user.save();

    res.json({ message: 'Treatment saved successfully', savedTreatments: user.savedTreatments });
  } catch (error) {
    next(error);
  }
};

