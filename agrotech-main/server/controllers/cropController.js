import fs from 'fs';

/**
 * @desc    Diagnose crop disease from uploaded image using Gemini Vision API
 * @route   POST /api/crops/diagnose
 * @access  Private
 */
export const diagnoseCrop = async (req, res, next) => {
  try {
    if (!req.file) {
      res.status(400);
      return next(new Error('Please upload an image of the crop'));
    }

    const { cropHint } = req.body;
    const imageBuffer = req.file.buffer;
    const mimeType = req.file.mimetype;

    // Call Gemini Vision helper
    console.log(`Diagnosing crop with hint: ${cropHint || 'Unknown'}`);
    const diagnosis = await diagnoseCropImage(imageBuffer, mimeType, cropHint || 'unknown');

    // Safe normalization of severity values
    let finalSeverity = 'Unknown';
    const allowedSeverities = ['Healthy', 'Mild', 'Moderate', 'Severe'];
    if (diagnosis && diagnosis.severity) {
      const match = allowedSeverities.find(
        s => s.toLowerCase() === diagnosis.severity.trim().toLowerCase()
      );
      if (match) {
        finalSeverity = match;
      } else {
        res.status(400);
        return next(new Error(`Invalid severity value generated by AI: '${diagnosis.severity}'`));
      }
    } else {
      res.status(400);
      return next(new Error('AI diagnosis did not return a severity rating'));
    }

    // Log info for debugging
    console.log('--- CROP DOCTOR LOG ---');
    console.log('uploaded filename:', req.file.originalname);
    console.log('MIME type:', mimeType);
    console.log('image buffer size:', req.file.size, 'bytes');
    console.log('crop hint:', cropHint || 'unknown');
    console.log('Gemini raw diagnosis result:', JSON.stringify(diagnosis, null, 2));
    console.log('parsed severity:', diagnosis.severity);
    console.log('final normalized severity:', finalSeverity);
    console.log('Gemini call success/failure: SUCCESS');
    console.log('------------------------');

    // Create a local virtual filepath for database logging
    // In production, you would upload this to S3/Cloudinary. We write to local static uploads folder.
    // To mock file storage in standard web app without blocking, we save a virtual or base64 data URI path or save to upload folder
    const fileName = `${Date.now()}_${req.file.originalname.replace(/\s+/g, '_')}`;
    const uploadDir = './uploads';
    if (!fs.existsSync(uploadDir)){
        fs.mkdirSync(uploadDir, { recursive: true });
    }
    const filePath = `uploads/${fileName}`;
    fs.writeFileSync(filePath, imageBuffer);

    // Save to database
    const newDiagnosis = await CropDiagnosis.create({
      userId: req.user._id,
      cropName: diagnosis.cropName || cropHint || 'Unknown Crop',
      diseaseName: diagnosis.diseaseName || 'Healthy',
      severity: finalSeverity,
      confidenceScore: diagnosis.confidenceScore || 0,
      causes: diagnosis.causes || [],
      preventionTips: diagnosis.preventionTips || [],
      treatment: {
        organic: diagnosis.treatment?.organic || '',
        chemical: diagnosis.treatment?.chemical || '',
        dosage: diagnosis.treatment?.dosage || '',
        precautions: diagnosis.treatment?.precautions || '',
      },
      imagePath: `/${filePath}`, // Serve statically from server
    });

    res.status(201).json(newDiagnosis);
  } catch (error) {
    console.log('--- CROP DOCTOR LOG ---');
    console.log('uploaded filename:', req.file ? req.file.originalname : 'none');
    console.log('MIME type:', req.file ? req.file.mimetype : 'none');
    console.log('image buffer size:', req.file ? req.file.size : 0, 'bytes');
    console.log('crop hint:', req.body ? req.body.cropHint : 'unknown');
    console.log('Gemini call success/failure: FAILURE');
    console.log('Error details:', error.message);
    console.log('------------------------');
    console.error('Error diagnosing crop:', error);
    next(error);
  }
};

