/**
 * @desc    Remove a saved treatment
 * @route   DELETE /api/crops/treatments/saved/:id
 * @access  Private
 */
export const removeSavedTreatment = async (req, res, next) => {
  try {
    const user = await User.findById(req.user._id);
    if (!user) {
      res.status(404);
      return next(new Error('User not found'));
    }

    user.savedTreatments = user.savedTreatments.filter(
      (t) => t._id.toString() !== req.params.id
    );
    await user.save();

    res.json({ message: 'Treatment removed', savedTreatments: user.savedTreatments });
  } catch (error) {
    next(error);
  }
};

/**
 * @desc    RAG Vector Scientific Treatment Finder
 * @route   POST /api/crops/treatments/search-rag
 * @access  Private
 */
export const searchScientificTreatmentsRAG = async (req, res, next) => {
  const { query } = req.body;

  if (!query || query.trim() === '') {
    res.status(400);
    return next(new Error('Query string is required'));
  }

  try {
    console.log('--- TREATMENT FINDER / RAG LOG ---');
    console.log('Received user query:', query);
    console.log('Pinecone query execution: START');

    // 1. Retrieve similar chunks from Vector Database
    const matchedDocs = await searchSimilarDocs(query, 3);
    
    console.log('Pinecone query execution: COMPLETED');
    console.log('Retrieved document identifiers/titles & similarity scores:');
    matchedDocs.forEach((doc, idx) => {
      console.log(`- Doc #${idx+1} Title: ${doc.title}, Source: ${doc.source}, Similarity Score: ${(doc.score * 100).toFixed(1)}%`);
    });

    // Combine chunks into single context
    const docsContext = matchedDocs
      .map((doc, idx) => `[Doc #${idx+1} - Source: ${doc.source} - Title: ${doc.title}]:\n${doc.text}`)
      .join('\n\n');

    console.log('Final prompt input summary context length:', docsContext.length, 'characters');

    // 2. Synthesize detailed, farmer-friendly response via Gemini
    const answer = await generateRAGTreatment(query, docsContext);

    console.log('Whether Gemini was called successfully: SUCCESS');
    console.log('----------------------------------');

    res.json({
      query,
      answer,
      sources: matchedDocs.map(doc => ({
        title: doc.title,
        source: doc.source,
        score: doc.score
      }))
    });
  } catch (error) {
    console.log('--- TREATMENT FINDER / RAG LOG ---');
    console.log('Whether Gemini was called successfully: FAILURE');
    console.log('Error details:', error.message);
    console.log('----------------------------------');
    next(error);
  }
};

