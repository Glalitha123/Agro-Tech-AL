// Aliases mapping for discrepant district names in government data.gov.in AGMARKNET records
export const DISTRICT_ALIASES = {
  "dr. b.r. ambedkar konaseema": ["dr.b.r.a.konaseema", "konaseema", "dr. b.r. ambedkar konaseema"],
  "ysr kadapa": ["ysr", "kadapa", "cuddapah", "ysr kadapa"],
  "sri potti sriramulu nellore": ["sps nellore", "nellore", "sri potti sriramulu nellore"],
  "ahmednagar": ["ahmednagar", "ahilyanagar"],
  "aurangabad": ["aurangabad", "chhatrapati sambhajinagar"],
  "osmanabad": ["osmanabad", "dharashiv"]
};

// Normalized helper mapping to match text input safely
const normalizeName = (name) => {
  if (!name) return '';
  return name.toLowerCase().trim().replace(/[^a-z0-9]/g, '');
};

// Resolves a list of query matches (including official and historical name variations)
export const getDistrictAliases = (districtName) => {
  if (!districtName) return [];
  const norm = normalizeName(districtName);
  const aliases = [norm];

  for (const [canonical, aliasList] of Object.entries(DISTRICT_ALIASES)) {
    const normCanonical = normalizeName(canonical);
    const normAliasList = aliasList.map(a => normalizeName(a));

    if (normCanonical === norm || normAliasList.includes(norm)) {
      normAliasList.forEach(a => {
        if (!aliases.includes(a)) {
          aliases.push(a);
        }
      });
      break;
    }
  }
  return aliases;
};
